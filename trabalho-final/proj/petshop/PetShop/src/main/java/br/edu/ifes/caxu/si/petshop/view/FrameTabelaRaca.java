    @Override
    public void runCallback() {
        if (confirmado.getOperacaoFeita()) {
            // recarrega tabela
            listaRaca.clear();
            listaRaca.addAll(DaoFactory.getDefaultDaoFactory().getRacaDao().getLista());
            tableModel.fireTableDataChanged();
        }
    }
