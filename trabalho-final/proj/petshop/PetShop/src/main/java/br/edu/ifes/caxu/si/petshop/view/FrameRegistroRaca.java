    @Override
    public void salvarEdicao() {
        registro.setNome(textFieldNome.getText());
        registro.setEspecie(listaEspecies.get(comboBoxEspecie.getSelectedIndex()));
        boolean resultado = false;
        if (registro.getId() == -1) {
            resultado = DaoFactory.getDefaultDaoFactory().getRacaDao().inserir(registro);
        } else {
            resultado = DaoFactory.getDefaultDaoFactory().getRacaDao().alterar(registro);
        }
        JOptionPane.showMessageDialog(this, 
                (resultado ? "Registro foi salvo." : "Erro ao salvar registro."), 
                "Edição", 
                JOptionPane.WARNING_MESSAGE);
        confirmed.setValue(resultado);
    }

    @Override
    public void cancelarEdicao() {
        confirmed.setValue(false);
    }
