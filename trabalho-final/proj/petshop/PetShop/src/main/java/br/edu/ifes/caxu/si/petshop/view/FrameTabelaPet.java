  @Override
  public void runCallback() {
    if (confirmado.getOperacaoFeita()) {
      // recarrega tabela
      listaPet.clear();
      listaPet.addAll(DaoFactory.getDefaultDaoFactory().getPetDao().getLista());
      tableModel.fireTableDataChanged();
    }
  }
