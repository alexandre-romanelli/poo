  private void buttonExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonExcluirActionPerformed
      if (JOptionPane.showConfirmDialog(this, "Confirma exclusão do registro selecionado?", "Exclusão", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
        int posAtual = tablePet.getSelectedRow();
        registroEmEdicao = listaPet.get(posAtual);
        boolean resultado = DaoFactory.getDefaultDaoFactory().getPetDao().excluir(registroEmEdicao);
        JOptionPane.showMessageDialog(this,
                (resultado ? "Registro foi excluído." : "Erro ao excluir registro."),
                "Exclusão",
                JOptionPane.WARNING_MESSAGE);
        if (resultado) {
          listaPet.remove(posAtual);
          tableModel.fireTableDataChanged();
          if (posAtual < listaPet.size()) {
            tablePet.setRowSelectionInterval(posAtual, posAtual);
          } else {
            tablePet.setRowSelectionInterval(listaPet.size() - 1, listaPet.size() - 1);
          }
        }
        
      }
  }//GEN-LAST:event_buttonExcluirActionPerformed

