    @Override
    public void runCallback() {
        if (confirmado.getOperacaoFeita()) {
            // recarrega tabela
            listaResponsavel.clear();
            listaResponsavel.addAll(DaoFactory.getDefaultDaoFactory().getResponsavelDao().getLista());
            tableModel.fireTableDataChanged();
        }
    }
