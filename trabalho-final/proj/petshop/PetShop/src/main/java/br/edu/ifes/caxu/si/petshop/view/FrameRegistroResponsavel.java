    private void mostrarRegistro() {
        this.textFieldNome.setText(registro.getId() >= 0 ? registro.getNome() : "");
        this.textFieldTelefone.setText(registro.getId() >= 0 ? registro.getTelefone(): "");
        this.textFieldEndereco.setText(registro.getId() >= 0 ? registro.getEndereco(): "");
    }
    
    @Override
    public void salvarEdicao() {
        registro.setNome(textFieldNome.getText());
        registro.setTelefone(textFieldTelefone.getText());
        registro.setEndereco(textFieldEndereco.getText());
        boolean resultado = false;
        if (registro.getId() == -1) {
            resultado = DaoFactory.getDefaultDaoFactory().getResponsavelDao().inserir(registro);
        } else {
            resultado = DaoFactory.getDefaultDaoFactory().getResponsavelDao().alterar(registro);
        }
        JOptionPane.showMessageDialog(this, 
                (resultado ? "Registro foi salvo." : "Erro ao salvar registro."), 
                "Edição", 
                JOptionPane.WARNING_MESSAGE);
        confirmed.setValue(resultado);
    }
    
    @Override
    public void cancelarEdicao() {
        confirmed.setValue(false);
    }
    
