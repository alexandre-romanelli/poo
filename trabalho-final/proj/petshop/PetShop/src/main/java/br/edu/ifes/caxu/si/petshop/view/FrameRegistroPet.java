  private void carregarComboBoxResponsavel() {
    listaResponsavel = DaoFactory.getDefaultDaoFactory().getResponsavelDao().getLista();
    comboBoxResponsavel.removeAllItems();
    for (Responsavel item : listaResponsavel) {
      comboBoxResponsavel.addItem(item.getNome());
    }
    if (!listaResponsavel.isEmpty()) {
      comboBoxResponsavel.setSelectedItem(listaResponsavel.get(0).getNome());
    }
  }
  
  private void carregarComboBoxEspecie() {
    listaEspecie = DaoFactory.getDefaultDaoFactory().getEspecieDao().getLista();
    comboBoxEspecie.removeAllItems();
    for (Especie item : listaEspecie) {
      comboBoxEspecie.addItem(item.getNome());
    }
    if (!listaEspecie.isEmpty()) {
      comboBoxEspecie.setSelectedIndex(0);
    }
  }
  
  private void carregarComboBoxRaca() {
    comboBoxRaca.removeAllItems();
    if (comboBoxEspecie.getSelectedIndex() != -1) {
      ArrayList<Raca> tempListaRaca = DaoFactory.getDefaultDaoFactory().getRacaDao().getLista();
      listaRaca.clear();
      int idEspecieSelecionada = listaEspecie.get(comboBoxEspecie.getSelectedIndex()).getId();
      for (Raca r : tempListaRaca) {
        if (r.getEspecie().getId() == idEspecieSelecionada) {
          listaRaca.add(r);
          comboBoxRaca.addItem(r.getNome());
        }
      }
    } else {
      listaRaca.clear();
    }
  }
  
  private void mostrarRegistro() {
    if (registro.getId() >= 0) {
      comboBoxResponsavel.setSelectedItem(registro.getResponsavel().getNome());
      textFieldNome.setText(registro.getNome());
      radioButtonGeneroMacho.setSelected((registro.getGenero() == 'M'));
      radioButtonGeneroFemea.setSelected(registro.getGenero() == 'F');
      comboBoxEspecie.setSelectedItem(registro.getEspecie().getNome());
      comboBoxRaca.setSelectedItem(registro.getRaca().getNome());
      SimpleDateFormat df = new SimpleDateFormat("yyyy-MM-dd");
      textFieldDataNascimento.setText(df.format(registro.getNascimento()));
    } else {
      comboBoxResponsavel.setSelectedItem(0);
      textFieldNome.setText("");
      radioButtonGeneroMacho.setSelected(true);
      radioButtonGeneroFemea.setSelected(false);
      comboBoxEspecie.setSelectedItem(0);
      comboBoxRaca.setSelectedItem(0);
      textFieldDataNascimento.setText("");
    }
  }
  
