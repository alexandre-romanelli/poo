  @Override
  public void salvarEdicao() {
    registro.setResponsavel(listaResponsavel.get(comboBoxResponsavel.getSelectedIndex()));
    registro.setNome(textFieldNome.getText());
    registro.setGenero(radioButtonGeneroMacho.isSelected() ? 'M' : 'F');
    registro.setEspecie(listaEspecie.get(comboBoxEspecie.getSelectedIndex()));
    registro.setRaca(listaRaca.get(comboBoxRaca.getSelectedIndex()));
    SimpleDateFormat df = new SimpleDateFormat("yyyy-MM-dd");
    try {
      Date dataNascimento = df.parse(textFieldDataNascimento.getText());
      registro.setNascimento(dataNascimento);
    } catch (ParseException ex) {
      JOptionPane.showMessageDialog(this, "Data de nascimento inválida. O formato válido é aaaa-mm-dd.", 
                                    "Erro", JOptionPane.ERROR_MESSAGE);
      return;
    }
    boolean resultado;
    if (registro.getId() == -1) {
      resultado = DaoFactory.getDefaultDaoFactory().getPetDao().inserir(registro);
    } else {
      resultado = DaoFactory.getDefaultDaoFactory().getPetDao().alterar(registro);
    }
    JOptionPane.showMessageDialog(this,
            (resultado ? "Registro foi salvo." : "Erro ao salvar registro."),
            "Edição",
            JOptionPane.WARNING_MESSAGE);
    confirmed.setValue(resultado);
  }

  @Override
  public void cancelarEdicao() {
    confirmed.setValue(false);
    this.setVisible(false);
  }

